def ok(t, who, scene):
    bad = [n for p, n in HARD if re.search(p, t)]
    said = (re.search(r'台詞：(.*)', t) or [None, ''])[1]   # 心裡知道可以，說出口才算說破
    if scene not in ('sunset', 'notebook', 'weeks') and re.search(LEAK, said): bad.append('說破味覺')
    if not all(k in t for k in ('動作：', '台詞：', '心：')): bad.append('格式')
    return bad


def run(scene, k):
    s, cast = S[scene], TAKES[k]
    seen, log = [], [f'# 即興 {scene} take{k + 1}（{"、".join(f"{w}={cast[w]}" for w in s["know"])}）', '']
    for who, now in s['beats']:
        p = ASK.format(who=who, card=CARD[who], know=s['know'][who], place=s['place'], goal=s['goal'][who], hide=s['hide'][who], line=s['line'][who],
                       seen='\n'.join(seen) or '（剛開始）', now=now or '輪到你。')
        out, bad = '', ['沒回']
        for _ in range(3):
            out = ACTORS[cast[who]](p).strip()
            bad = ok(out, who, scene) if out else ['沒回']
            if not bad: break
        g = {m.group(1): m.group(2).strip() for m in re.finditer(r'(動作|台詞|心)：(.*)', out)}
        if now: seen.append(f'（{now}）'); log.append(f'> {now}')
        seen.append(f'{who}［動作］{g.get("動作", "")}　［說］{g.get("台詞", "")}')   # 心聲不進別人的逐字稿
        log += [f'**{who}**　動作：{g.get("動作", "")}', f'　台詞：{g.get("台詞", "")}', f'　心：{g.get("心", "")}' + (f'　〔沒過：{"、".join(bad)}〕' if bad else ''), '']
    OUT.mkdir(parents=True, exist_ok=True)
    (OUT / f'{scene}-{k + 1}.md').write_text('\n'.join(log), encoding='utf-8')
    return scene, k


